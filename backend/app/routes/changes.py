from fastapi import APIRouter, HTTPException, Query
from app.database import get_db

router = APIRouter(prefix="/changes", tags=["Change Detection"])


@router.get("/events")
def get_change_events(region_id: int = None):
    """Returns detected change events from the operational schema view."""
    try:
        with get_db() as cur:
            query = """
                SELECT 
                    change_id,
                    region_id,
                    region_name,
                    region_type,
                    from_land_cover,
                    to_land_cover,
                    start_date,
                    end_date,
                    duration_days,
                    changed_area_sq_km
                FROM operational.vw_change_event_details
            """
            params = []
            if region_id:
                query += " WHERE region_id = %s "
                params.append(region_id)
            query += " ORDER BY changed_area_sq_km DESC;"

            cur.execute(query, tuple(params))
            return cur.fetchall()
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/compare")
def compare_landcover(
    region_id: int = Query(1, description="Region ID to compare"),
    date_start: str = Query("2021-01-01", description="Initial observation date (YYYY-MM-DD)"),
    date_end: str = Query("2024-10-01", description="Final observation date (YYYY-MM-DD)")
):
    """Executes the stored procedure operational.fn_compare_landcover to calculate shifts."""
    try:
        with get_db() as cur:
            cur.execute("""
                SELECT 
                    land_cover_name,
                    initial_area_sq_km,
                    final_area_sq_km,
                    net_change_sq_km,
                    change_pct
                FROM operational.fn_compare_landcover(%s, %s::DATE, %s::DATE);
            """, (region_id, date_start, date_end))
            results = cur.fetchall()
            return {
                "region_id": region_id,
                "date_start": date_start,
                "date_end": date_end,
                "shifts": results
            }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/available-dates")
def get_available_dates(region_id: int = Query(1)):
    """Returns distinct observation dates available for a region."""
    try:
        with get_db() as cur:
            cur.execute("""
                SELECT DISTINCT observation_date 
                FROM operational.observation 
                WHERE region_id = %s 
                ORDER BY observation_date;
            """, (region_id,))
            return [str(r["observation_date"]) for r in cur.fetchall()]
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@router.get("/audit-log")
def get_change_audit_log():
    """Returns audit log records generated by the change event trigger."""
    try:
        with get_db() as cur:
            cur.execute("""
                SELECT 
                    audit_id,
                    action_type,
                    change_id,
                    region_id,
                    changed_area,
                    logged_at
                FROM operational.change_event_audit
                ORDER BY logged_at DESC
                LIMIT 20;
            """)
            return cur.fetchall()
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
